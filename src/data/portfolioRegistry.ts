export function getEntryBySlug(slug: string) {
  return portfolioRegistry.find((entry) => entry.slug === slug);
}

export function getEntriesByGroup(group: (typeof portfolioGroups)[number]) {
  return portfolioRegistry
    .filter((entry) => entry.group === group)
    .sort((a, b) => a.displayOrder - b.displayOrder);
}
